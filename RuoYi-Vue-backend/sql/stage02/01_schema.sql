CREATE TABLE biz_company_user (
 id bigint NOT NULL AUTO_INCREMENT PRIMARY KEY COMMENT '主键',
 company_id bigint NOT NULL COMMENT '企业', user_id bigint NOT NULL COMMENT '若依账号',
 status varchar(20) NOT NULL DEFAULT 'ACTIVE' COMMENT 'ACTIVE/LEFT',
 active_user bigint GENERATED ALWAYS AS (CASE WHEN status='ACTIVE' THEN user_id ELSE NULL END) STORED,
 create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE KEY uk_active_user(active_user), UNIQUE KEY uk_membership(company_id,user_id),
 FOREIGN KEY(company_id) REFERENCES biz_company(id), FOREIGN KEY(user_id) REFERENCES sys_user(user_id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='企业归属关系；同账号仅一有效企业';