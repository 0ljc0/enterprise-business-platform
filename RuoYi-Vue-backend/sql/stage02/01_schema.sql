CREATE TABLE biz_task (
  id bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  company_id bigint NULL COMMENT '企业归属，服务端控制',
  task_code varchar(50) NOT NULL UNIQUE COMMENT '全局任务编号',
  title varchar(150) NOT NULL COMMENT '任务标题',
  publisher_type varchar(20) NOT NULL DEFAULT 'COMPANY' COMMENT 'PLATFORM/COMPANY',
  description text COMMENT '任务说明',
  project_id bigint COMMENT '所属项目',
  target_quantity decimal(18,2) NOT NULL DEFAULT 0 COMMENT '目标工作量',
  unit varchar(20) NOT NULL DEFAULT '件' COMMENT '工作量单位',
  signup_deadline datetime COMMENT '报名截止时间',
  start_date date COMMENT '开始日期',
  end_date date COMMENT '结束日期',
  status varchar(20) NOT NULL DEFAULT 'DRAFT' COMMENT '业务状态',
  version int NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  create_by varchar(64) NOT NULL DEFAULT '' COMMENT '创建人',
  create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by varchar(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  remark varchar(500) NOT NULL DEFAULT '' COMMENT '备注',
  PRIMARY KEY(id),
  UNIQUE KEY uk_company_id(company_id,id),
  KEY idx_scope_status(company_id,status,id),
  FOREIGN KEY(company_id) REFERENCES biz_company(id),
  CHECK(publisher_type IN ('PLATFORM','COMPANY')),
  CHECK((publisher_type='PLATFORM' AND company_id IS NULL) OR (publisher_type='COMPANY' AND company_id IS NOT NULL)),
  CHECK(target_quantity>=0),
  FOREIGN KEY(company_id,project_id) REFERENCES biz_project(company_id,id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='任务';

