CREATE TABLE biz_company (
  id bigint NOT NULL AUTO_INCREMENT COMMENT '主键',
  company_name varchar(100) NOT NULL COMMENT '企业名称',
  credit_code char(18) NOT NULL UNIQUE COMMENT '统一社会信用代码',
  contact_name varchar(50) COMMENT '联系人',
  contact_phone varchar(30) COMMENT '电话',
  address varchar(255) COMMENT '地址',
  status varchar(20) NOT NULL DEFAULT 'DRAFT' COMMENT '业务状态',
  version int NOT NULL DEFAULT 0 COMMENT '乐观锁版本',
  create_by varchar(64) NOT NULL DEFAULT '' COMMENT '创建人',
  create_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP COMMENT '创建时间',
  update_by varchar(64) NOT NULL DEFAULT '' COMMENT '更新人',
  update_time datetime NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP COMMENT '更新时间',
  remark varchar(500) NOT NULL DEFAULT '' COMMENT '备注',
  PRIMARY KEY(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='企业';

